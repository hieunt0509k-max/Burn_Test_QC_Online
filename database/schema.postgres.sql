CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
  po_number TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  UNIQUE(customer_id, po_number)
);

CREATE TABLE IF NOT EXISTS burn_tests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE RESTRICT,
  product_code TEXT NOT NULL,
  diameter_mm DOUBLE PRECISION,
  height_mm DOUBLE PRECISION,
  fragrance TEXT,
  color TEXT,
  wick TEXT,
  temperature_c DOUBLE PRECISION,
  test_date TEXT,
  test_time TEXT,
  start_datetime TEXT,
  end_datetime TEXT,
  total_burn_time TEXT,
  tester TEXT,
  approver TEXT,
  result TEXT NOT NULL DEFAULT 'PENDING',
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  material_types TEXT
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'admin',
  created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS app_deleted_purchase_orders (
  purchase_order_id BIGINT PRIMARY KEY,
  deleted_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS burn_test_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  burn_test_id BIGINT NOT NULL REFERENCES burn_tests(id) ON DELETE CASCADE,
  slot INTEGER NOT NULL,
  file_name TEXT NOT NULL,
  file_url TEXT NOT NULL,
  original_name TEXT,
  mime_type TEXT,
  file_size BIGINT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  UNIQUE(burn_test_id, slot)
);

CREATE TABLE IF NOT EXISTS burn_test_videos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  burn_test_id BIGINT NOT NULL REFERENCES burn_tests(id) ON DELETE CASCADE,
  file_name TEXT NOT NULL,
  file_url TEXT NOT NULL,
  original_name TEXT,
  mime_type TEXT NOT NULL,
  file_size BIGINT NOT NULL,
  duration_seconds DOUBLE PRECISION NOT NULL,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS customer_check_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE RESTRICT,
  customer_code TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  UNIQUE(purchase_order_id, customer_code)
);

CREATE TABLE IF NOT EXISTS customer_check_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id BIGINT NOT NULL REFERENCES customer_check_records(id) ON DELETE CASCADE,
  burn_hours DOUBLE PRECISION NOT NULL,
  file_name TEXT NOT NULL,
  file_url TEXT NOT NULL,
  original_name TEXT,
  mime_type TEXT,
  file_size BIGINT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS customer_check_slots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id BIGINT NOT NULL REFERENCES customer_check_records(id) ON DELETE CASCADE,
  burn_hours DOUBLE PRECISION NOT NULL,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  UNIQUE(record_id, burn_hours)
);

CREATE TABLE IF NOT EXISTS burn_test_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  burn_test_id BIGINT NOT NULL REFERENCES burn_tests(id) ON DELETE CASCADE,
  time_label TEXT NOT NULL,
  wick_status TEXT NOT NULL,
  flame_status TEXT NOT NULL,
  wick_height_mm DOUBLE PRECISION NOT NULL,
  vessel_condition TEXT NOT NULL,
  temperature_c DOUBLE PRECISION NOT NULL,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
  product_code TEXT NOT NULL,
  size TEXT,
  weight DOUBLE PRECISION,
  wick TEXT,
  color TEXT,
  fragrance TEXT,
  diameter_mm DOUBLE PRECISION,
  height_mm DOUBLE PRECISION,
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  image_blob BYTEA,
  image_hash TEXT,
  image_url TEXT
);

CREATE TABLE IF NOT EXISTS app_settings (
  key TEXT PRIMARY KEY,
  value TEXT,
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS qc_standards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  criterion TEXT NOT NULL,
  min_value TEXT,
  max_value TEXT,
  unit TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  customer_id BIGINT REFERENCES customers(id)
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL,
  detail TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS sample_burn_tests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
  purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE SET NULL,
  product_code TEXT NOT NULL,
  product_name TEXT,
  size TEXT,
  weight DOUBLE PRECISION,
  wick_spec TEXT,
  test_date TEXT,
  tester TEXT,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  start_at TEXT,
  end_at TEXT,
  burn_total_seconds BIGINT,
  overall_result TEXT NOT NULL DEFAULT 'PENDING',
  is_running INTEGER NOT NULL DEFAULT 0,
  current_phase TEXT NOT NULL DEFAULT 'BURN',
  phase_started_at TEXT,
  phase_elapsed_seconds BIGINT NOT NULL DEFAULT 0,
  last_saved_at TEXT,
  total_burn_time TEXT,
  start_datetime TEXT,
  end_datetime TEXT,
  test_result TEXT DEFAULT 'PENDING',
  approved TEXT
);

CREATE TABLE IF NOT EXISTS sample_burn_test_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_test_id BIGINT NOT NULL REFERENCES sample_burn_tests(id) ON DELETE CASCADE,
  slot INTEGER NOT NULL,
  file_name TEXT NOT NULL,
  file_url TEXT NOT NULL,
  original_name TEXT,
  mime_type TEXT,
  file_size BIGINT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  UNIQUE(sample_test_id, slot)
);

CREATE TABLE IF NOT EXISTS sample_burn_cycles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_test_id BIGINT NOT NULL REFERENCES sample_burn_tests(id) ON DELETE CASCADE,
  cycle_no INTEGER NOT NULL,
  phase TEXT NOT NULL CHECK(phase IN ('BURN','REST')),
  start_at TEXT NOT NULL,
  end_at TEXT,
  duration_seconds BIGINT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS qc_units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS periodic_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS periodic_template_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES periodic_templates(id) ON DELETE CASCADE,
  item_name TEXT NOT NULL,
  standard TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS periodic_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  check_date TEXT NOT NULL,
  check_time TEXT,
  area TEXT,
  process TEXT,
  shift TEXT,
  inspector TEXT,
  check_type TEXT,
  template_id BIGINT REFERENCES periodic_templates(id) ON DELETE SET NULL,
  overall_result TEXT NOT NULL DEFAULT 'PASS',
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS periodic_check_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  check_id BIGINT NOT NULL REFERENCES periodic_checks(id) ON DELETE CASCADE,
  item_name TEXT NOT NULL,
  standard TEXT,
  actual TEXT,
  result TEXT NOT NULL DEFAULT 'PASS',
  root_cause TEXT,
  corrective_action TEXT,
  owner TEXT,
  deadline TEXT,
  status TEXT NOT NULL DEFAULT 'Closed',
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE INDEX IF NOT EXISTS idx_po_customer ON purchase_orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_test_po ON burn_tests(purchase_order_id);
CREATE INDEX IF NOT EXISTS idx_photo_test ON burn_test_photos(burn_test_id);
CREATE INDEX IF NOT EXISTS idx_customer_check_record ON customer_check_photos(record_id, burn_hours, id);
CREATE INDEX IF NOT EXISTS idx_customer_check_slot ON customer_check_slots(record_id, burn_hours);
CREATE UNIQUE INDEX IF NOT EXISTS idx_customer_check_order_code_unique
  ON customer_check_records(purchase_order_id, lower(customer_code));
CREATE INDEX IF NOT EXISTS idx_log_test ON burn_test_logs(burn_test_id);
CREATE INDEX IF NOT EXISTS idx_product_order ON products(order_id);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_sample_test_date ON sample_burn_tests(test_date);
CREATE INDEX IF NOT EXISTS idx_sample_test_po ON sample_burn_tests(purchase_order_id);
CREATE INDEX IF NOT EXISTS idx_sample_test_photo ON sample_burn_test_photos(sample_test_id);
CREATE INDEX IF NOT EXISTS idx_sample_cycle_test ON sample_burn_cycles(sample_test_id, cycle_no, phase);
CREATE INDEX IF NOT EXISTS idx_qc_standards_customer ON qc_standards(customer_id);
CREATE INDEX IF NOT EXISTS idx_periodic_template_item ON periodic_template_items(template_id, sort_order, id);
